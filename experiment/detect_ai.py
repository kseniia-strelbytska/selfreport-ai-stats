"""Zero-shot AI-text detection experiment (plan §16).

The ~7B model is asked, without any detector training, whether a held-out
document was written by a human or generated by an AI.  Held-out documents
come from the ``holdout_evidence`` pool (never trained on) of every source
provenance that exists: ``control`` (procedural human-style writer), ``ai``
(the ~10B generator) and ``ai_alt`` (a second generator, if configured).

Scoring uses next-token log-probabilities of the two answer words rather than
free generation, so every document gets a continuous score for AUROC as well
as a hard label for accuracy / precision / recall / F1 / confusion matrix.

Outputs ``results/<name>/seed<seed>/detection/{scores.jsonl,summary.json}``.
Per-world scores are kept so ``experiment.analysis`` can ask whether
detectability *predicts* provenance effects on learning - while the README
insists that detecting AI text and weighting it differently are separate
hypotheses.
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np

from experiment.config import Config, resolve_path
from experiment.dataset import corpus_specs
from experiment.observability import get_logger
from experiment.story_generator import documents_path, load_documents
from experiment.utils import write_json, write_jsonl

log = get_logger("detect")

PROMPTS = [
    "Read the following text carefully.\n\n<text>\n{text}\n</text>\n\nWas this text written by a human or generated by an AI language model? Answer with exactly one word: HUMAN or AI.",
    "Below is a passage of prose.\n\n{text}\n\nDecide who produced it. Reply with a single word, either HUMAN (a person wrote it) or AI (a language model generated it).",
    "You are an expert at spotting machine-generated writing. Classify the passage.\n\n---\n{text}\n---\n\nYour verdict (one word, HUMAN or AI):",
]


# --------------------------------------------------------------------------- #
# Metrics
# --------------------------------------------------------------------------- #


def auroc(scores: list[float], labels: list[int]) -> float:
    """Rank-based AUROC (Mann-Whitney U), positive class = 1 (AI)."""
    pos = [s for s, y in zip(scores, labels, strict=True) if y == 1]
    neg = [s for s, y in zip(scores, labels, strict=True) if y == 0]
    if not pos or not neg:
        return float("nan")
    allv = sorted(scores)
    # average ranks with ties
    ranks: dict[float, float] = {}
    i = 0
    while i < len(allv):
        j = i
        while j + 1 < len(allv) and allv[j + 1] == allv[i]:
            j += 1
        for k in range(i, j + 1):
            ranks[allv[k]] = (i + j) / 2 + 1
        i = j + 1
    r_pos = sum(ranks[s] for s in pos)
    u = r_pos - len(pos) * (len(pos) + 1) / 2
    return float(u / (len(pos) * len(neg)))


def classification_metrics(
    pred: list[int], labels: list[int], scores: list[float] | None = None
) -> dict[str, Any]:
    tp = sum(1 for p, y in zip(pred, labels, strict=True) if p == 1 and y == 1)
    tn = sum(1 for p, y in zip(pred, labels, strict=True) if p == 0 and y == 0)
    fp = sum(1 for p, y in zip(pred, labels, strict=True) if p == 1 and y == 0)
    fn = sum(1 for p, y in zip(pred, labels, strict=True) if p == 0 and y == 1)
    n = tp + tn + fp + fn
    precision = tp / (tp + fp) if tp + fp else float("nan")
    recall = tp / (tp + fn) if tp + fn else float("nan")
    f1 = (
        2 * precision * recall / (precision + recall)
        if (tp + fp and tp + fn and (precision + recall) > 0)
        else float("nan")
    )
    out = {
        "n": n,
        "accuracy": (tp + tn) / n if n else float("nan"),
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "confusion": {"tp": tp, "tn": tn, "fp": fp, "fn": fn},
        "positive_class": "AI",
    }
    if scores is not None:
        out["auroc"] = auroc(scores, labels)
    return out


# --------------------------------------------------------------------------- #
# Scoring with the model
# --------------------------------------------------------------------------- #


class LabelScorer:
    """log p(AI) - log p(HUMAN) for the first answer token, given a prompt."""

    def __init__(self, cfg: Config) -> None:
        import torch

        from experiment.evaluate import ModelAnswerer

        self.answerer = ModelAnswerer(cfg)
        self.tok = self.answerer.tokenizer
        self._torch = torch
        self.label_ids = {}
        for label in ("AI", "HUMAN"):
            ids = set()
            for variant in (label, " " + label, label.capitalize(), " " + label.capitalize()):
                enc = self.tok(variant, add_special_tokens=False)["input_ids"]
                if enc:
                    ids.add(enc[0])
            self.label_ids[label] = sorted(ids)

    def use_adapter(self, adapter_dir, name):
        self.answerer.use_adapter(adapter_dir, name)

    def use_pretrained(self):
        self.answerer.use_pretrained()

    def score(self, prompts: list[str]) -> list[dict[str, float]]:
        torch = self._torch
        model = self.answerer.model
        out: list[dict[str, float]] = []
        bs = self.answerer.batch_size
        for i in range(0, len(prompts), bs):
            batch = prompts[i : i + bs]
            rendered = [self.answerer._chat(self.tok, p, None) for p in batch]
            enc = self.tok(rendered, return_tensors="pt", padding=True, add_special_tokens=False).to(
                model.device
            )
            with torch.inference_mode():
                if self.answerer.active is None and self.answerer.peft is not None:
                    with self.answerer.peft.disable_adapter():
                        logits = model(**enc).logits[:, -1, :]
                else:
                    logits = model(**enc).logits[:, -1, :]
            logp = torch.log_softmax(logits.float(), dim=-1)
            for row in logp:
                lp_ai = torch.logsumexp(row[self.label_ids["AI"]], dim=0).item()
                lp_h = torch.logsumexp(row[self.label_ids["HUMAN"]], dim=0).item()
                out.append(
                    {
                        "logp_ai": lp_ai,
                        "logp_human": lp_h,
                        "score": lp_ai - lp_h,
                        "mass": math.exp(lp_ai) + math.exp(lp_h),
                    }
                )
        return out


