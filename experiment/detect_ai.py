# Driver
# --------------------------------------------------------------------------- #


def collect_heldout(cfg: Config) -> list[dict[str, Any]]:
    """Held-out documents per (world, condition of the primary arm, provenance)."""
    n_per = int(cfg.detection.num_documents_per_source)
    max_chars = int(cfg.detection.get("max_chars", 4000))
    docs: list[dict[str, Any]] = []
    seen_keys = set()
    for spec in corpus_specs(cfg):
        if spec.arm != "primary":
            continue
        for prov in ("control", "ai", "ai_alt"):
            key = (spec.world_id, spec.condition, prov)
            if key in seen_keys or not documents_path(cfg, spec.world_id, spec.condition, prov).exists():
                continue
            seen_keys.add(key)
            pool = [
                d
                for d in load_documents(cfg, spec.world_id, spec.condition, prov)
                if d["role"] == "holdout_evidence"
            ]
            if not pool:  # fall back to validation-like evidence docs if no holdout pool
                pool = [
                    d
                    for d in load_documents(cfg, spec.world_id, spec.condition, prov)
                    if d["role"] == "evidence"
                ][-n_per:]
            for d in pool[:n_per]:
                docs.append(
                    {
                        "document_id": d["document_id"],
                        "world_id": spec.world_id,
                        "theme_id": d["theme_id"],
                        "condition": spec.condition,
                        "provenance": prov,
                        "label": 0 if prov == "control" else 1,
                        "generator_model": d.get("generator_model"),
                        "text": d["text"][:max_chars],
                        "actual_word_count": d.get("actual_word_count"),
                    }
                )
    return docs


def run(cfg: Config) -> int:
    if not bool(cfg.detection.get("enabled", True)):
        log.info("detection disabled")
        return 0
    docs = collect_heldout(cfg)
    provs = {d["provenance"] for d in docs}
    if len(provs) < 2:
        log.warning("detection needs at least two provenances (have %s); skipping", provs)
        return 0
    n_variants = int(cfg.detection.prompt_variants)
    scorer = LabelScorer(cfg)
    scorer.use_pretrained()
    rows: list[dict[str, Any]] = []
    for v in range(min(n_variants, len(PROMPTS))):
        prompts = [PROMPTS[v].format(text=d["text"]) for d in docs]
        scores = scorer.score(prompts)
        for d, s in zip(docs, scores, strict=True):
            rows.append(
                {
                    **{k: val for k, val in d.items() if k != "text"},
                    "prompt_variant": v,
                    **s,
                    "pred": int(s["score"] > 0),
                }
            )
    # aggregate per document over prompt variants
    by_doc: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        by_doc.setdefault(r["document_id"], []).append(r)
    per_doc = []
    for rs in by_doc.values():
        m = float(np.mean([r["score"] for r in rs]))
        per_doc.append(
            {
                **{
                    k: v
                    for k, v in rs[0].items()
                    if k not in ("prompt_variant", "logp_ai", "logp_human", "score", "mass", "pred")
                },
                "score": m,
                "pred": int(m > 0),
            }
        )
    labels = [d["label"] for d in per_doc]
    preds = [d["pred"] for d in per_doc]
    sc = [d["score"] for d in per_doc]
    summary: dict[str, Any] = {
        "model": scorer.answerer.checkpoint,
        "n_documents": len(per_doc),
        "by_provenance_counts": {p: sum(1 for d in per_doc if d["provenance"] == p) for p in provs},
        "overall": classification_metrics(preds, labels, sc),
        "by_prompt_variant": {},
        "by_world": {},
        "mean_answer_mass": float(np.mean([r["mass"] for r in rows])),
    }
    for v in range(min(n_variants, len(PROMPTS))):
        rv = [r for r in rows if r["prompt_variant"] == v]
        summary["by_prompt_variant"][str(v)] = classification_metrics(
            [r["pred"] for r in rv], [r["label"] for r in rv], [r["score"] for r in rv]
        )
    for wid in sorted({d["world_id"] for d in per_doc}):
        rw = [d for d in per_doc if d["world_id"] == wid]
        summary["by_world"][wid] = classification_metrics(
            [d["pred"] for d in rw], [d["label"] for d in rw], [d["score"] for d in rw]
        )
    out = (
        resolve_path(cfg, "experiment.results_root", "results")
        / str(cfg.experiment.name)
        / f"seed{int(cfg.experiment.seed)}"
        / "detection"
    )
    write_jsonl(out / "scores.jsonl", rows)
    write_jsonl(out / "scores_per_document.jsonl", per_doc)
    write_json(out / "summary.json", summary)
    o = summary["overall"]
    log.info(
        "detection: n=%d acc=%.3f F1=%s AUROC=%s confusion=%s",
        o["n"],
        o["accuracy"],
        o["f1"],
        o.get("auroc"),
        o["confusion"],
    )
    return 0


